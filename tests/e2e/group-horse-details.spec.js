import {test,expect} from '@playwright/test'
import {horses} from '../../dev/fixtures.js'
async function expand(page){for(const item of await page.locator('.rca-group-horse-details > summary').all())if(!await item.evaluate(el=>el.parentElement.open))await item.click()}

test('every grouped horse opens its own detail and keyboard return preserves the draft',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.clock.setFixedTime(new Date('2026-11-15T06:31:00Z'))
  await page.goto('/market-preview.html?state=groups-horse-details')
  await page.getByLabel('観測時点').selectOption('demo-1')
  await page.getByText('以前の配分・購入記録機能',{exact:true}).click()
  await page.getByLabel('１レースの予算上限').fill('9000')
  await page.getByLabel('判断の根拠・不確かな点').fill('編集中の根拠を残したまま能力を見る')
  const boundary=page.getByLabel('1番の前で区切る',{exact:true})
  const expectedBoundary=!await boundary.isChecked();await boundary.setChecked(expectedBoundary)
  await expand(page)
  const cardLinks=page.locator('.rca-group-horses').getByRole('button')
  await expect(cardLinks).toHaveCount(8)
  const before=await page.evaluate(()=>JSON.stringify(localStorage))
  for(const h of horses){
    const link=page.locator('.rca-group-horses').getByRole('button',{name:`${h.no}番 ${h.name}の詳細`,exact:true})
    await link.focus();await link.press('Enter')
    await expect(page.getByRole('heading',{name:`${h.no} ${h.name}の詳細`,exact:true})).toBeVisible()
    await expect(page.getByLabel('表示する馬')).toHaveValue(String(h.no))
    await expect(page.getByRole('region',{name:'各馬の評価',exact:true}).getByRole('article')).toHaveCount(1)
    await expect(page.getByRole('heading',{name:'今回の評価',exact:true})).toBeVisible()
    await expect(page.getByRole('heading',{name:'過去の実績',exact:true})).toBeVisible()
    await expect(page.getByRole('heading',{name:'パドック・直前情報',exact:true})).toBeVisible()
    await expect(page.getByText('選択オッズの取得時点 11/15 15:20 までの情報に限定しています。',{exact:true})).toBeVisible()
    await expect(page.getByLabel('１レースの予算上限')).toBeHidden()
    const back=page.getByRole('button',{name:'← グループ・買い目へ戻る',exact:true})
    await expect(back).toBeFocused();await back.press('Enter')
    await expect(link).toBeFocused()
    await expect(page.getByLabel('観測時点')).toHaveValue('demo-1')
    await expect(page.getByLabel('１レースの予算上限')).toHaveValue('9000')
    await expect(page.getByLabel('判断の根拠・不確かな点')).toHaveValue('編集中の根拠を残したまま能力を見る')
    await expect(boundary).toBeChecked({checked:expectedBoundary})
  }
  expect(await page.evaluate(()=>JSON.stringify(localStorage))).toBe(before)
  const table=page.getByRole('table',{name:'グループのカスタマイズ',exact:true})
  await table.getByRole('button',{name:'3番 架空馬Cの詳細',exact:true}).click()
  await expect(page.getByRole('heading',{name:'3 架空馬Cの詳細',exact:true})).toBeVisible()
  expect(errors).toEqual([])
})

test('mobile horse links have usable touch targets, preserve scroll on return, and handle missing evidence',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/market-preview.html?state=groups-horse-mobile')
  await expand(page)
  const link=page.locator('.rca-group-horses').getByRole('button',{name:'7番 架空馬Gの詳細',exact:true})
  await link.scrollIntoViewIfNeeded()
  const box=await link.boundingBox();expect(box.height).toBeGreaterThanOrEqual(44)
  const y=await page.evaluate(()=>scrollY)
  await link.click()
  await expect(page.getByRole('heading',{name:'7 架空馬Gの詳細',exact:true})).toBeVisible()
  await expect(page.getByText('旧取得方式のためコメント記録なし',{exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({path:'.qa/group-horse-detail-mobile.jpg',fullPage:false})
  await page.getByLabel('表示する馬').selectOption('8')
  await expect(page.getByRole('heading',{name:'8 架空馬Hの詳細',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'← グループ・買い目へ戻る',exact:true}).click()
  await expect(link).toBeFocused()
  expect(Math.abs(await page.evaluate(()=>scrollY)-y)).toBeLessThan(3)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
