import {expect,test} from '@playwright/test'
import {race,horses,demoSnapshots} from '../../dev/fixtures.js'
import {createCompanionService,createCompanionHandler} from '../../server/companion.js'
import {memoryStore,request} from '../fixtures/companion.js'

const odds={1:3,2:3.5,3:8,4:9,5:20,6:25,7:80,8:100}
const history=()=>demoSnapshots().filter(s=>Date.parse(s.observedAt)<=Date.parse('2026-11-15T06:20:00Z')).map(s=>({...s,odds}))
async function open(page,state='personal-flow') {
  await page.clock.setFixedTime(new Date('2026-11-15T06:25:00Z'))
  await page.addInitScript(({race,state,events})=>{
    const key=`race-ability-odds:v1:synthetic-demo-${state}:${race.raceDate}:${race.id}`
    if(!localStorage.getItem(key))localStorage.setItem(key,JSON.stringify(events))
  },{race,state,events:history()})
  await page.goto(`/market-preview.html?state=${state}`)
  await page.getByRole('button',{name:'新しい予想を入力する',exact:true}).click()
}
const ledger=page=>page.evaluate(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('race-forecast-ledger:')))))
async function formation(page) {
  await page.getByRole('group',{name:'1着のグループ',exact:true}).getByRole('checkbox',{name:/^B/}).check()
  await page.getByRole('group',{name:'2着のグループ',exact:true}).getByRole('checkbox',{name:/^A/}).check()
}

test('personal exacta freezes grouping through sync, saves plans separately and reconciles results after reload',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await open(page)
  const save=page.getByRole('button',{name:'私の予想を登録する',exact:true})
  await expect(save).toBeDisabled()
  await formation(page)
  const numbers=page.getByRole('region',{name:'選択グループの馬番',exact:true})
  await expect(numbers.getByRole('group',{name:'1着の馬番',exact:true})).toContainText('馬番 3・4')
  await expect(numbers.getByRole('group',{name:'2着の馬番',exact:true})).toContainText('馬番 1・2')
  const tickets=page.getByRole('table',{name:'私の予想の買い目',exact:true})
  await expect(tickets).toBeVisible()
  await expect(tickets.locator('tbody tr th')).toHaveText(['馬単 3→1','馬単 3→2','馬単 4→1','馬単 4→2'])
  await page.getByLabel('1点の予定金額',{exact:true}).fill('500')
  await page.getByLabel('予想メモ',{exact:true}).fill('B勝ち・A2着を試す')
  // A new observation changes the live grouping, not the source of the open draft.
  await page.evaluate(({race,events})=>localStorage.setItem(`race-ability-odds:v1:synthetic-demo-personal-flow:${race.raceDate}:${race.id}`,JSON.stringify([{...events[0],id:'new-source',odds:{1:8,2:9,3:3,4:3.5,5:20,6:25,7:80,8:100}},...events])),{race,events:history()})
  await page.getByRole('button',{name:'同期データを再読込（開発確認）'}).click()
  await expect(page.getByRole('group',{name:'1着のグループ',exact:true})).toContainText('3 架空馬C')
  await expect(numbers.getByRole('group',{name:'1着の馬番',exact:true})).toContainText('馬番 3・4')
  await save.click()
  const saved=page.getByRole('region',{name:'保存したグループ判断'})
  await expect(saved).toContainText('4点・投入予定 2,000円')
  await expect(saved).toContainText('馬単｜フォーメーション｜B → A')
  const first=(await ledger(page)).groupPlans[0]
  expect(first.snapshot.odds[3]).toBe(8)
  expect(first.slots).toEqual([['B'],['A'],[]])
  expect(first.mode).toBe('live')
  expect((await ledger(page)).purchases).toEqual([])
  await page.reload()
  await expect(saved).toContainText('B勝ち・A2着を試す')
  await page.evaluate(async({race,horses})=>{
    const {applyCloudData}=await import('/src/cloudStore.js')
    await applyCloudData('synthetic-demo-personal-flow',race,horses,{race:{...race,horses},observations:[{kind:'LIVE_RACE',eventId:'personal-result',retrievedAt:'2026-11-15T07:00:00Z',payload:{raceId:race.id,raceDate:race.raceDate,releaseFieldSize:8,priceStatus:'final-visible',results:[3,1,5,2,4,6,7,8].map((horseNo,i)=>({horseNo,rank:i+1}))}}]})
  },{race,horses})
  await page.getByRole('button',{name:'同期データを再読込（開発確認）'}).click()
  await expect(saved).toContainText('配分した買い目：的中')
  await page.getByText('この案の実購入・払戻を記録する',{exact:true}).click()
  await expect(page.getByLabel('実購入した買い目と金額')).toHaveValue(/馬単 3-1 500/)
  expect((await ledger(page)).purchases).toEqual([])
  expect((await ledger(page)).groupPlans[0]).toEqual(first)
  expect(errors).toEqual([])
})

