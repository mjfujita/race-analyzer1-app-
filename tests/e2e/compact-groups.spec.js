import {test,expect} from '@playwright/test'

const card=(page,label)=>page.getByRole('article',{name:`${label}グループ`,exact:true})
async function open(page){
  await page.clock.setFixedTime(new Date('2026-11-15T06:31:00Z'))
  await page.setViewportSize({width:390,height:844})
  await page.goto('/market-preview.html?state=groups-local-review')
}

test('collapsed group cards keep the outlook and prediction buttons visible; customization fits mobile',async({page})=>{
  await open(page)
  for(const label of ['A','B']){
    await expect(card(page,label).getByRole('region',{name:`${label}群の推定確率`,exact:true})).toBeVisible()
    await expect(card(page,label).locator('.rca-group-horse-details')).not.toHaveAttribute('open')
    await expect(card(page,label).getByRole('list',{name:`${label}グループの馬`,exact:true})).toBeHidden()
  }
  for(const text of ['最新の保存済み観測を表示中です。','観測時点はJRDBのオッズ時刻','発走時刻を過ぎたレースです。','次の馬のオッズが設定倍率以上','取得元：','馬名を押すと、その馬の評価','確率の参照上限：'])await expect(page.getByText(text,{exact:false})).toHaveCount(0)
  const a=card(page,'A')
  await a.locator('.rca-group-horse-details > summary').click()
  await expect(a.getByRole('article',{name:/の予想指標$/})).toBeVisible()
  await a.locator('.rca-group-horse-details > summary').click()
  await expect(a.getByRole('region',{name:'A群の推定確率',exact:true})).toBeVisible()
  const table=page.getByRole('table',{name:'グループのカスタマイズ',exact:true})
  await expect(table.getByRole('columnheader')).toHaveText(['区切り','群・馬番・馬名','単勝','候補'])
  await table.scrollIntoViewIfNeeded()
  const bounds=await table.boundingBox();expect(bounds.x+bounds.width).toBeLessThanOrEqual(390)
  await expect(table).not.toContainText('IDM')
  await page.getByLabel('6番の前で区切る',{exact:true}).check()
  await expect(page.getByRole('article',{name:'Cグループ',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({path:'.qa/compact-customize-mobile.jpg',fullPage:false})
})

test('card selections open a frozen personal draft with horse numbers, then save separately from purchases',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await open(page)
  await page.getByLabel('カードから追加する券種').selectOption('馬単')
  await card(page,'A').getByRole('button',{name:'A群を1着に追加',exact:true}).click()
  await expect(card(page,'A').getByRole('button',{name:'A群を1着に追加',exact:true})).toHaveAttribute('aria-pressed','true')
  await card(page,'B').getByRole('button',{name:'B群を2着に追加',exact:true}).click()
  await card(page,'B').getByRole('button',{name:'買い目を確認（7点）',exact:true}).click()
  const composer=page.getByRole('region',{name:'私の予想を入力',exact:true})
  await expect(composer).toBeVisible()
  await expect.poll(()=>page.evaluate(()=>window.scrollY)).toBe(0)
  await expect(composer.getByRole('group',{name:'1着の馬番',exact:true})).toContainText('馬番 2')
  await expect(composer.getByRole('group',{name:'2着の馬番',exact:true})).toContainText('馬番 1・3・4・5・6・7・8')
  await expect(composer.getByRole('table',{name:'私の予想の買い目',exact:true}).locator('tbody tr')).toHaveCount(7)
  await page.getByRole('button',{name:'同期データを再読込（開発確認）'}).click()
  await expect(composer.getByRole('group',{name:'1着の馬番',exact:true})).toContainText('馬番 2')
  await composer.getByRole('button',{name:'私の予想を登録する',exact:true}).click()
  await expect(page.getByRole('region',{name:'保存したグループ判断',exact:true})).toContainText('馬単 · 7点 · 対象 8頭')
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('race-prediction-journal:')))))
  expect(saved.predictions[0].slots).toEqual([['A'],['B'],[]]);expect(saved.predictions[0].budget).toBeUndefined()
  expect(errors).toEqual([])
})

test('trifecta and trio cards support third place and reset an unconfirmed selection when the observation changes',async({page})=>{
  await open(page)
  await expect(page.getByLabel('カードから追加する券種')).toHaveValue('3連単')
  for(const label of ['A','B'])await expect(card(page,label).getByRole('button',{name:`${label}群を3着に追加`,exact:true})).toBeVisible()
  await card(page,'A').getByRole('button',{name:'A群を1着に追加',exact:true}).click()
  await card(page,'B').getByRole('button',{name:'B群を2着に追加',exact:true}).click()
  await expect(card(page,'B').getByRole('button',{name:'買い目を確認（0点）',exact:true})).toBeDisabled()
  await card(page,'B').getByRole('button',{name:'B群を3着に追加',exact:true}).click()
  await expect(card(page,'B').getByRole('button',{name:'買い目を確認（42点）',exact:true})).toBeEnabled()
  await card(page,'B').getByRole('button',{name:'買い目を確認（42点）',exact:true}).click()
  const composer=page.getByRole('region',{name:'私の予想を入力',exact:true})
  await expect(composer.getByLabel('券種',{exact:true})).toHaveValue('3連単')
  await expect(composer.getByRole('group',{name:'3着の馬番',exact:true})).toContainText('馬番 1・3・4・5・6・7・8')
  await expect(composer.getByRole('table',{name:'私の予想の買い目',exact:true}).locator('tbody tr')).toHaveCount(42)
  await page.getByRole('button',{name:'同期データを再読込（開発確認）'}).click()
  await expect(composer.getByRole('group',{name:'3着の馬番',exact:true})).toContainText('馬番 1・3・4・5・6・7・8')
  await page.getByRole('button',{name:'入力をやめて戻る',exact:true}).click()
  await page.getByLabel('観測時点').selectOption('demo-1')
  await expect(card(page,'B').getByRole('button',{name:'B群を2着に追加',exact:true})).toHaveAttribute('aria-pressed','false')
  await page.getByLabel('カードから追加する券種').selectOption('3連複')
  await card(page,'A').getByRole('button',{name:'A群を1頭目に追加',exact:true}).click()
  await card(page,'B').getByRole('button',{name:'B群を2頭目に追加',exact:true}).click()
  await card(page,'B').getByRole('button',{name:'B群を3頭目に追加',exact:true}).click()
  await card(page,'B').getByRole('button',{name:'買い目を確認（21点）',exact:true}).click()
  await expect(page.getByLabel('券種',{exact:true})).toHaveValue('3連複')
  await expect(page.getByRole('table',{name:'私の予想の買い目',exact:true}).locator('tbody tr')).toHaveCount(21)
})
