import {test,expect} from '@playwright/test'
test('result comparison includes saved predictions, result-only races and pending races without an anchor tab',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const calls=[];page.on('request',r=>{if(r.url().includes('/api/companion'))calls.push(r.url())})
  await page.goto('/market-preview.html?state=results-local-review')
  await expect(page.getByRole('heading',{name:'レース結果と予想',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:/軸候補/})).toHaveCount(0)
  const comparison=page.getByRole('group',{name:'このレースの予想と結果',exact:true})
  await expect(comparison.getByRole('region',{name:'保存した予想',exact:true})).toContainText('A → C → C')
  await expect(comparison.getByRole('region',{name:'このレースの結果',exact:true})).toContainText('A → B → C')
  const table=page.getByRole('table',{name:'予想と結果の組み合わせ'})
  await expect(table.locator('tbody tr')).toHaveCount(3)
  const resultOnly=table.getByRole('row').filter({has:page.getByRole('button',{name:'東京12Rの予想と結果を開く'})})
  await expect(resultOnly).toContainText('予想未登録');await expect(resultOnly).toContainText('4 → 2 → 7');await expect(resultOnly).toContainText('23,450円')
  await expect(table.getByRole('row').filter({has:page.getByRole('button',{name:'京都10Rの予想と結果を開く'})})).toContainText('結果待ち')
  await page.setViewportSize({width:1280,height:1000});await page.screenshot({path:'.qa/results-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  const bounds=await table.boundingBox();expect(bounds.x+bounds.width).toBeLessThanOrEqual(390)
  for(const cell of await table.locator('tbody tr').first().locator('td').all()){const b=await cell.boundingBox();expect(b.x).toBeGreaterThanOrEqual(0);expect(b.x+b.width).toBeLessThanOrEqual(390)}
  await page.screenshot({path:'.qa/results-mobile.png',fullPage:true})
  await page.getByLabel('結果一覧の会場').selectOption('東京');await expect(table.locator('tbody tr')).toHaveCount(1)
  await table.getByRole('button',{name:'東京12Rの予想と結果を開く'}).click()
  await expect(page.getByRole('group',{name:'このレースの予想と結果'})).toContainText('4 → 2 → 7')
  await expect(page.getByRole('group',{name:'このレースの予想と結果'})).toContainText('このレースの予想はまだ登録されていません。')
  expect(errors).toEqual([]);expect(calls).toEqual([])
})
