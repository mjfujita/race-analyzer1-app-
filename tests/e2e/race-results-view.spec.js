import {test,expect} from '@playwright/test'
test('opens with whole-day group tendencies including unpredicted races and keeps race comparison available',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const calls=[];page.on('request',r=>{if(r.url().includes('/api/companion'))calls.push(r.url())})
 await page.goto('/market-preview.html?state=results-local-review')
 await expect(page.getByRole('heading',{name:'レース結果と予想',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:/軸候補/})).toHaveCount(0)
 const trends=page.getByRole('region',{name:'当日の全レース・グループ傾向'})
 await expect(trends).toContainText('開催 3レース ／ 結果 2レース ／ グループ集計 2レース')
 await expect(trends).toContainText('自分の登録 1・自動 1')
 await expect(page.getByRole('group',{name:'このレースの予想と結果'})).toHaveCount(0)
 const table=page.getByRole('table',{name:'全レースのグループ結果'})
 await expect(table.locator('tbody tr')).toHaveCount(3)
 const resultOnly=table.getByRole('row').filter({has:page.getByRole('button',{name:'東京12Rの詳細を開く'})})
 await expect(resultOnly).toContainText('自動・締切前');await expect(resultOnly).toContainText('B群');await expect(resultOnly).toContainText('4番');await expect(resultOnly).toContainText('A群');await expect(resultOnly).toContainText('2番');await expect(resultOnly).toContainText('D群');await expect(resultOnly).toContainText('7番')
 await expect(table.getByRole('row').filter({has:page.getByRole('button',{name:'京都10Rの詳細を開く'})})).toContainText('結果待ち')
 // Summary appears before the whole-day table, without an intervening prediction form.
 const tally=page.getByRole('table',{name:'全レースのグループ別着順回数'})
 expect((await tally.boundingBox()).y).toBeLessThan((await table.boundingBox()).y)
 await expect(tally.getByRole('row').filter({has:page.getByRole('rowheader',{name:'A',exact:true})})).toContainText('1回')
 await page.setViewportSize({width:1280,height:1000});await page.screenshot({path:'.qa/all-results-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
 for(const cell of await table.locator('tbody tr').first().locator('td').all()){const b=await cell.boundingBox();expect(b.x).toBeGreaterThanOrEqual(0);expect(b.x+b.width).toBeLessThanOrEqual(390)}
 await page.screenshot({path:'.qa/all-results-mobile.png',fullPage:true})
 await page.getByLabel('グループ傾向の会場').selectOption('東京');await expect(table.locator('tbody tr')).toHaveCount(1);await expect(trends).toContainText('グループ集計 1レース')
 await table.getByRole('button',{name:'東京12Rの詳細を開く'}).click()
 await expect(page.getByRole('group',{name:'このレースの予想と結果'})).toContainText('4 → 2 → 7')
 await expect(page.getByRole('group',{name:'このレースの予想と結果'})).toContainText('このレースの予想はまだ登録されていません。')
 await page.getByRole('button',{name:'当日のグループ傾向',exact:true}).click();await expect(table.locator('tbody tr')).toHaveCount(3)
 expect(errors).toEqual([]);expect(calls).toEqual([])
})
test('missing observations keep all results visible and never require saving a prediction',async({page})=>{
 await page.goto('/market-preview.html?state=results-local-review')
 await page.evaluate(()=>{for(const key of Object.keys(localStorage))if(key.startsWith('race-ability-odds:'))localStorage.removeItem(key)})
 await page.getByRole('button',{name:'同期データを再読込（開発確認）'}).click()
 const table=page.getByRole('table',{name:'全レースのグループ結果'})
 await expect(table.locator('tbody tr')).toHaveCount(3)
 const resultOnly=table.getByRole('row').filter({has:page.getByRole('button',{name:'東京12Rの詳細を開く'})})
 await expect(resultOnly).toContainText('分類待ち');await expect(resultOnly).toContainText('4番')
 await expect(page.getByRole('region',{name:'当日の全レース・グループ傾向'})).toContainText('全頭のオッズ待ち')
})
test('zero saved predictions and zero registrations still show every available group result',async({page})=>{
 await page.goto('/market-preview.html?state=results-local-review')
 await page.evaluate(()=>{
  for(const key of Object.keys(localStorage)){
   if(key.startsWith('race-prediction-journal:')){const value=JSON.parse(localStorage.getItem(key));value.predictions=[];localStorage.setItem(key,JSON.stringify(value))}
   if(key.startsWith('race-group-registration:'))localStorage.removeItem(key)
  }
 })
 await page.getByRole('button',{name:'結果一覧を再読込',exact:true}).click()
 const trends=page.getByRole('region',{name:'当日の全レース・グループ傾向'})
 await expect(trends).toContainText('開催 3レース ／ 結果 2レース ／ グループ集計 2レース')
 await expect(trends).toContainText('自分の登録 0・自動 2')
 await expect(page.getByRole('table',{name:'全レースのグループ結果'}).locator('tbody tr')).toHaveCount(3)
 expect(await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('race-group-registration:')))).toEqual([])
 await expect(page.getByRole('button',{name:'新しい予想を入力する',exact:true})).toHaveCount(0)
})
