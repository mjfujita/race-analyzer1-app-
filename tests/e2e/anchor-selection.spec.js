import { expect, test } from '@playwright/test'

test('two anchors keep their probabilities and observed prices after manual selection, save and reload', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-15T06:30:00Z'))
  await page.goto('/market-preview.html?state=anchors')
  await expect(page.getByRole('heading', { name: '軸馬2頭とレースの妙味' })).toBeVisible()
  await expect(page.getByLabel('予算上限（円）')).toHaveCount(0)
  await page.getByLabel('軸馬1', { exact: true }).selectOption('8')
  await page.getByLabel('軸馬2', { exact: true }).selectOption('7')
  await expect(page.getByLabel('軸馬2', { exact: true }).locator('option[value="8"]')).toBeDisabled()
  await page.getByLabel('軸馬を選んだ理由・判断メモ').fill('展開を確認し、8番と7番を選択')
  await page.getByRole('button', { name: '2頭の軸馬と判断を固定保存' }).click()
  const frozen = page.getByLabel('保存時の2頭軸')
  await expect(frozen).toContainText('固定した軸馬 8番 架空馬H ／ 7番 架空馬G')
  const originalSummary = await frozen.textContent()
  const ledger = await page.evaluate(() => {
    const key = Object.keys(localStorage).find(name => name.startsWith('race-forecast-ledger:v1:'))
    return JSON.parse(localStorage.getItem(key))
  })
  expect(ledger.forecasts).toHaveLength(2)
  expect(ledger.forecasts[0].kind).toBe('ace')
  expect(ledger.forecasts[1].kind).toBe('user')
  expect(ledger.forecasts[1].parameters.anchorSelection.selected).toEqual([8, 7])
  expect(ledger.forecasts[1].allocations).toEqual([])
  expect(ledger.purchases).toEqual([])
  expect(ledger.forecasts[1].metrics.invested).toBe(0)
  expect(ledger.forecasts[1].field.map(horse => horse.probability)).toEqual(ledger.forecasts[0].field.map(horse => horse.probability))
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '.qa/two-anchors-mobile.png', fullPage: true })
  await page.reload()
  await expect(frozen).toHaveText(originalSummary)
  await page.getByLabel('オッズ下落の想定（%）').fill('80')
  await expect(frozen).toHaveText(originalSummary)
  await page.getByLabel('オッズ下落の想定（%）').fill('81')
  await expect(page.getByRole('button', { name: '2頭の軸馬と判断を固定保存' })).toBeDisabled()
})

test('missing observations hold the value assessment and prevent saving', async ({ page }) => {
  await page.goto('/market-preview.html?state=empty')
  await page.getByRole('button', { name: '軸馬2頭・妙味判断', exact: true }).click()
  await expect(page.getByText('判断保留', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: /2頭の軸馬.*保存/ })).toBeDisabled()
})
